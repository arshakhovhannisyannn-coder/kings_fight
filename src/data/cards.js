export function isLegendary(cardId) {
  const t = CARDS[cardId].type;
  return t === 'hero' || t === 'special';
}
export function isPlaceable(def) { return def.type !== 'spell'; }

/** Validate a deck against config.deckLimits. Returns { ok, errors: [Armenian strings] }. */
export function validateDeck(deck, cfg, allowed = null) {
  const errors = [];
  if (!Array.isArray(deck) || deck.length !== cfg.deckSize) errors.push(`Կապուկը պետք է ունենա ուղիղ ${cfg.deckSize} քարտ։`);
  const counts = {};
  let legendary = 0;
  for (const id of deck || []) {
    const def = CARDS[id];
    if (!def || def.token) { errors.push(`Անհայտ քարտ՝ ${id}`); continue; }
    if (allowed && !allowed.includes(id)) errors.push(`«${def.nameHy}» քարտը դեռ բացված չէ։`);
    counts[id] = (counts[id] || 0) + 1;
    if (isLegendary(id)) legendary++;
  }
  for (const id of Object.keys(counts)) {
    const def = CARDS[id];
    const max = cfg.deckLimits.maxCopies[def.type];
    if (counts[id] > max) errors.push(max === 1 ? `«${def.nameHy}» քարտը կրկնվում է. բոլոր քարտերը պետք է տարբեր լինեն։` : `«${def.nameHy}»՝ առավելագույնը ${max} օրինակ։`);
  }
  if (legendary > cfg.deckLimits.maxLegendary) errors.push(`Առավելագույնը ${cfg.deckLimits.maxLegendary} լեգենդար քարտ (հերոս/հատուկ)։`);
  return { ok: errors.length === 0, errors };
}
